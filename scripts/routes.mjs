// `npm run docs:api`: writes docs/API.md from the route files (no server needed).
import fs from "node:fs";
import path from "node:path";

const dir = "server/routes";
const PREFIX = { "chat.js": "/api/chat", "uploads.js": "/api/uploads", "ai.js": "/api/ai" };
const rows = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".js")).sort()) {
  const src = fs.readFileSync(path.join(dir, file), "utf8");
  const re = /router\.(get|post|put|patch|delete)\(\s*["']([^"']+)["']/g;
  for (let m; (m = re.exec(src)); ) rows.push([m[1].toUpperCase(), (PREFIX[file] || "/api") + m[2], file.replace(".js", "")]);
}
const out = [
  "# API",
  "",
  "Generated by `npm run docs:api`. Auth is a session cookie or `Authorization: Bearer <token>`; errors are `{ \"error\": \"message\" }`.",
  "",
  "| Method | Path | Group |",
  "| --- | --- | --- |",
  ...rows.map(([m, p, g]) => `| ${m} | \`${p}\` | ${g} |`),
  "",
].join("\n");
fs.writeFileSync("docs/API.md", out);
console.log(`docs/API.md: ${rows.length} routes`);
